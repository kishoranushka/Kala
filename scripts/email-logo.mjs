/* Builds the logo embedded in order emails: brand/kala-logo-horizontal-dark.png, trimmed and sized for email,
   written as base64 into api/_lib/email-logo.js (so the serverless functions need no file access).
   Run: node scripts/email-logo.mjs */
import fs from 'node:fs';
import sharp from 'sharp';

const src = new URL('../brand/kala-logo-horizontal-dark.png', import.meta.url);
const out = new URL('../api/_lib/email-logo.js', import.meta.url);

/* 2× the 200px display width, for sharp rendering on retina screens */
const png = await sharp(src.pathname.replace(/^\/(\w:)/, '$1'))
  .trim({ threshold: 10 })
  .extend({ top: 4, bottom: 4, left: 4, right: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .resize({ width: 400 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();
const { width, height } = await sharp(png).metadata();

fs.writeFileSync(out, `/* generated by scripts/email-logo.mjs — do not edit */
export const LOGO = { width: ${width}, height: ${height}, base64: '${png.toString('base64')}' };
`);
console.log(`email logo ${width}×${height}, ${(png.length / 1024).toFixed(1)} KB`);
